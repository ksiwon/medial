"""Bring the exhibition record (은점마을 사흘 · 9경로) into the sim database.

    python scripts/import_exhibition.py            # bundle -> local-data/runs/sim.sqlite3
    python scripts/import_exhibition.py --replace  # move the existing sim copy aside first

The exhibition wall (docs D108) was generated by its own pipeline, archived in
``local-archive/exhibition-2026-09-28/``: rule-planned days, one model call per
Task for the dialogue, one per resident for the day's review, and every one of
the three requests run to the next day - one opening setting, 3 second days, 9
third days (13 days in all; the other two opening settings the record once had
are no longer made). This copies that record into the shape the app reads, so
the sim version plays exactly that: the same Tasks, lines, reviews and branches.

It is *not* a record the app's engine produced, and nothing pretends it is:
every attempt says ``dataSource = exhibition-record``, the session says where
it came from, and the dialogue is carried as stored scenes (``scenes_json``)
instead of being dressed up as engine events. The event log holds one
``task.started`` / ``task.completed`` pair per Task - what happened, not what
was said. Re-creating these days with the app's own engine is future work
(DEVELOPMENT.md).

Nothing from the bundle is committed: it and the database stay git-ignored. The
names are the pseudonyms of the anonymised persona pack the bundle was built
from, and they reach the browser only at runtime, from this database.
"""
