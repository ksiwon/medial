def values_for(node: dict[str, Any], by_id: dict[str, dict[str, Any]]) -> dict[str, dict[str, Any]]:
    chain = []
    cursor: dict[str, Any] | None = node
    while cursor is not None:
        chain.append(cursor)
        cursor = by_id.get(cursor["parent"]) if cursor["parent"] is not None else None
    root, *later = reversed(chain)
    values = json.loads(json.dumps({**BASE, **INITIAL[root["choice"]["id"]]}))
    for step in later:
        option = step["choice"]
        values[option["ruleType"]] = {**values[option["ruleType"]], **option["after"]}
    return values


def policy_of(node: dict[str, Any], values: dict[str, dict[str, Any]], parent_id: str | None) -> PolicyRevision:
    order = values["contact_order"]
    params = PolicyParams(
        retryCount=values["retry_before_help"]["count"],
        retryIntervalMin=values["retry_before_help"]["intervalMinutes"],
        quietWindowMin=values["quiet_period"]["minutes"],
        helperContactCap=values["helper_daily_cap"]["perDay"],
        neighbourAskLimit=values["neighbour_ask_limit"]["people"],
        disclosure=values["disclosure_scope"]["level"],
        escalateToInstitutionAfterMin=values["institution_deadline"]["afterMinutes"],
        allowHeadContact=order["allowHeadContact"],
        rideCandidateOrder=values["ride_candidate_order"]["order"],
        maxRideDetourMin=values["ride_detour_limit"]["maxDetourMinutes"],
    )
    policy = PolicyRevision(
        id="policy-exh-%s" % node["id"], parentId=parent_id,
        coreItem="응답이 없거나 도움이 필요할 때 누구의 시간으로 해결할 것인가",
        label=node["choice"]["title"],
        changes=[node["choice"].get("because") or node["choice"].get("title")],
        contactStrategy=ContactStrategy(order["strategy"]), params=params)
    # The bundle's own sentences must be what these values say, word for word
    # but for the one the app has since sharpened ("전화로 다시 연락").
    for rule in node["policy"]:
        ours = semantic_rules.format_rule(
            rule["ruleType"], semantic_rules.read_values(rule["ruleType"], policy.model_dump(mode="json")))
        if ours.replace("전화로 ", "") != rule["sentence"]:
            raise SystemExit("규칙 값이 묶음의 문장과 다릅니다 (%s %s): %r != %r"
                             % (node["id"], rule["ruleType"], ours, rule["sentence"]))
    return policy


# ------------------------------------------------------------------ the map
def to_world(matrix: list[float]):
    a, b, c, d, e, f = matrix
    return lambda p: [round(a * p[0] + c * p[1] + e, 1), round(b * p[0] + d * p[1] + f, 1)]


def along(path: list[list[float]], u: float) -> list[float]:
    if len(path) == 1:
        return path[0]
    lengths = [((path[i][0] - path[i - 1][0]) ** 2 + (path[i][1] - path[i - 1][1]) ** 2) ** 0.5
               for i in range(1, len(path))]
    target, walked = sum(lengths) * max(0.0, min(1.0, u)), 0.0
    for i, length in enumerate(lengths):
        if walked + length >= target:
            k = (target - walked) / length if length else 0
            return [path[i][0] + (path[i + 1][0] - path[i][0]) * k,
                    path[i][1] + (path[i + 1][1] - path[i][1]) * k]
        walked += length
    return path[-1]


class Where:
    """Where each person is, minute by minute - the wall's ``posOf``, ported so
    the map shows what the wall showed. Coordinates are the source raster's."""

    def __init__(self, bundle: dict[str, Any], node: dict[str, Any]):
        self.b, self.node = bundle, node
        self.start, self.step = bundle["clock"]["start"], bundle["clock"]["step"]

    def _index(self, t: int, pid: str) -> int:
        return max(0, min(len(self.b["place"][pid]) - 1, round((t - self.start) / self.step)))

    def word(self, pid: str, t: int) -> str:
        return self.b["place"][pid][self._index(t, pid)]

    def track(self, pid: str, t: float) -> list[float] | None:
        rows = self.b["track"][pid]
        i = (t - self.start) / self.step
        a = max(0, int(i))
        z = min(a + 1, len(rows) - 1)
        pa, pb = rows[min(a, len(rows) - 1)], rows[z]
        if not pa or not pb:
            return pa or pb or None
        u = i - a
        return [pa[0] + (pb[0] - pa[0]) * u, pa[1] + (pb[1] - pa[1]) * u]

    def at(self, pid: str, t: int, *, baseline: bool = False) -> dict[str, Any]:
        """``{p, why, task, car, moving, driver}`` - ``p`` is None off the map."""
        moves = [] if baseline else self.node["moves"]
        for mv in moves:
            for leg in mv["legs"]:
                if leg.get("rider") == pid and leg["from"] <= t <= leg["to"]:
                    return {"p": along(leg["path"], (t - leg["from"]) / max(1, leg["to"] - leg["from"])),
                            "task": mv["taskId"], "car": True, "moving": len(leg["path"]) > 1,
                            "driver": mv["who"]}
        word = self.word(pid, t)
        if word in OFF_MAP_WORDS:
            return {"p": None, "why": OFF_MAP_WORDS[word], "word": word}
        if not baseline:
            for ab in self.node.get("absences") or []:
                if ab["who"] == pid and ab["from"] <= t < ab["to"]:
                    return {"p": None, "why": ab["label"], "word": word}
        for mv in moves:
            if mv["who"] != pid:
                continue
            for leg in mv["legs"]:
                if leg["from"] <= t <= leg["to"]:
                    return {"p": along(leg["path"], (t - leg["from"]) / max(1, leg["to"] - leg["from"])),
                            "task": mv["taskId"], "car": bool(mv.get("car")),
                            "moving": len(leg["path"]) > 1, "riders": [l["rider"] for l in [leg] if l.get("rider")]}
        base = self.track(pid, t)
        for mv in moves:
            if mv["who"] != pid or t <= mv["endAt"] or t - mv["endAt"] > 120:
                continue
            end = mv["legs"][-1]["path"][-1]
            if base and ((base[0] - end[0]) ** 2 + (base[1] - end[1]) ** 2) ** 0.5 > 25:
                return {"p": end, "word": word}
        if base is None:
            return {"p": None, "why": word, "word": word}
        return {"p": base, "word": word}


def segments(where: Where, pid: str, world, *, baseline: bool) -> list[dict[str, Any]]:
    """The person's day as the app's Segments, one sample a minute."""
    b = where.b
    start, end = b["clock"]["start"], b["clock"]["end"]
    out: list[dict[str, Any]] = []
    prev = None
    for t in range(start, end + 1):
        s = where.at(pid, t, baseline=baseline)
        moving = bool(s.get("moving")) and s["p"] is not None
        if s["p"] is None:
            key = ("off", s.get("why"))
        elif moving:
            key = ("move", s.get("task"), bool(s.get("car")), tuple(s.get("riders") or ()), s.get("driver"))
        else:
            key = ("stay", round(s["p"][0], 1), round(s["p"][1], 1), s.get("task"), s.get("word"))
        point = world(s["p"]) if s["p"] is not None else None
        if prev is not None and prev["key"] == key and (key[0] != "stay" or True):
            seg = out[-1]
            seg["endMs"] = (t + 1) * MINUTE
            if moving:
                seg["polyline"].append(point)
            continue
        word = s.get("word") or where.word(pid, t)
        place = PLACE_WORDS.get(word)
        place = ("HOME:%s" % pid) if place == "HOME" else place
        seg: dict[str, Any] = {
            "startMs": t * MINUTE, "endMs": (t + 1) * MINUTE,
            "kind": "travel" if moving else "stay",
            "origin": "task" if s.get("task") else "baseline",
            "label": s.get("why") or ("이동 중" if moving else word),
            "place": None if moving else ("SEA" if key[0] == "off" and word == "조업 구역"
                                          else "TOWN" if key[0] == "off" else place),
            "fromPlace": None, "toPlace": None,
            "mode": ("drive" if s.get("car") else "walk") if moving else ("offmap" if key[0] == "off" else "stay"),
            "metres": 0, "requestId": s.get("task"), "interruptible": True,
        }
        if key[0] == "off":
            seg["offMap"] = True
        if moving:
            seg["polyline"] = [point]
        elif point is not None:
            seg["xy"] = point
        if s.get("riders"):
            seg["riders"] = list(s["riders"])
        out.append(seg)
        prev = {"key": key}
    return out


# ------------------------------------------------------------------ one day
def build_day(bundle: dict[str, Any], node: dict[str, Any], village, policy: PolicyRevision,
              attempt_id: str, parent_attempt: str | None, names: dict[str, str]) -> tuple[Any, dict[str, list[str]]]:
    world = to_world(village.map_image["northUpMatrix"])
    scene = bundle["scenes"][node["key"]]
    transcripts = scene["transcripts"]
    tasks = sorted(node["tasks"], key=lambda t: (hhmm(t["start"]), t["id"]))

    events: list[DomainEvent] = []
    seq = 0

    def emit(kind: EventType, at_ms: int, who: str, task: dict[str, Any], payload: dict[str, Any]) -> DomainEvent:
        nonlocal seq
        seq += 1
        people = sorted({actor(a) for a in task["actors"]} | ({task["about"]} if task.get("about") else set()))
        event = DomainEvent(
            id="ev-%d" % seq, attemptId=attempt_id, seq=seq, simTimeMs=at_ms, type=kind, actorId=who,
            correlationId=task["id"], visibility=sorted({"researcher", *people}), payload=payload)
        events.append(event)
        return event

    episodes: list[dict[str, Any]] = []
    panels: dict[str, Any] = {}
    experienced: dict[str, list[str]] = {}
    for task in tasks:
        lead = actor(next((a for a in task["actors"] if a != "MED"), "MED"))
        payload = {"requestId": task["id"], "task": task["type"], "title": task["title"],
                   "questId": task["questId"], "outcome": task["outcome"], "channel": task["channel"]}
        if task.get("about"):
            payload["subjectId"] = task["about"]
        started = emit(EventType.task_started, hhmm(task["start"]), lead, task, payload)
        lines = (transcripts.get(task["id"]) or {}).get("lines") or []
        beats = []
        for index, beat in enumerate(task["beats"]):
            frames = []
            for frame in beat["frames"]:
                target = frame["target"]
                owner = frame.get("owner")
                place = ("HOME:%s" % owner if target == "HOME" else "CAR:%s" % owner if target == "CAR"
                         else "INST:HC_NURSE" if target == "CLINIC" else target)
                who = [actor(w) for w in frame["who"]]
                frames.append({"key": "%s|%s" % (place, frame["label"]), "place": place,
                               "label": frame["label"], "device": frame.get("device"), "who": who,
                               "poses": {actor(k): v for k, v in (frame.get("poses") or {}).items()}})
            said = [{"seq": started.seq, "kind": "say", "speaker": actor(line["speaker"]),
                     "text": line["text"]} for line in lines if line["beat"] == index]
            beats.append({
                "requestId": task["id"], "firstSeq": started.seq, "lastSeq": started.seq,
                "startMs": hhmm(beat["at"]), "endMs": hhmm(beat["until"]), "frames": frames,
                "cast": [actor(c) for c in beat["cast"]], "medial": "MED" in beat["cast"],
                "waiting": beat.get("waiting"), "lines": said})
        # One Task is one event on screen; a silence of three minutes or more
        # between its beats goes back to the map (beats.ts MAP_GAP_MS).
        current = None
        for beat in beats:
            if current is None or beat["startMs"] - current["endMs"] >= 3 * MINUTE:
                current = {"requestId": task["id"], "subjectId": task.get("about"), "title": task["title"],
                           "firstOfRequest": current is None, "startMs": beat["startMs"],
                           "endMs": beat["endMs"], "beats": []}
                episodes.append(current)
            current["beats"].append(beat)
            current["endMs"] = max(current["endMs"], beat["endMs"])
        m = task["medial"]
        subject = task.get("about")
        # A kind of event the screen has no word for must stop the import: letting its key through
        # once put "quest:morning-remark" on a judgement panel (2026-10-06).
        if task["questId"] not in QUEST_WORDS:
            raise SystemExit("화면에 쓸 이름이 없는 사건입니다: %s (QUEST_WORDS 에 더합니다)" % task["questId"])
        panels[task["id"]] = {
            "subtitle": "%s%s" % (QUEST_WORDS[task["questId"]],
                                  (" · %s %s" % (subject, names.get(subject, ""))).rstrip() if subject else ""),
            "judgment": {
                "question": None, "knows": list(m.get("knows") or []),
                "rules": [{"label": semantic_rules.spec(r).label,
                           "sentence": semantic_rules.format_rule(
                               r, semantic_rules.read_values(r, policy.model_dump(mode="json")))}
                          for r in task.get("rules") or []],
                "asked": [{"actorId": actor(v["who"]), "verdict": VERDICT.get(v["result"], "told"),
                           "heard": v.get("heard")} for v in m.get("verdicts") or []],
                "ruledOut": [], "told": list(m.get("says") or []) or None,
                "withheld": list(m.get("withholds") or []),
                "rationale": None, "result": None,
            },
        }
        finished = emit(EventType.task_completed, hhmm(task["end"]), lead, task,
                        {"requestId": task["id"], "outcome": task["outcome"]})
        for who in {actor(a) for a in task["actors"]} | ({subject} if subject else set()):
            experienced.setdefault(who, []).append(started.id)
    episodes.sort(key=lambda e: (e["startMs"], e["beats"][0]["firstSeq"]))

    where = Where(bundle, node)
    actors = {}
    for person in bundle["people"]:
        pid = person["id"]
        realized = segments(where, pid, world, baseline=False)
        base = segments(where, pid, world, baseline=True)
        actors[pid] = {
            "id": pid, "displayName": pid, "isVillageHead": person.get("job") == "이장",
            "group": next((r["group"] for r in village.residents if r["id"] == pid), "unknown"),
            "homeXY": world([person["home"]["x"], person["home"]["y"]]),
            "baseline": base, "realized": realized,
            "planChanged": any(s["origin"] == "task" for s in realized),
            "addedTaskMs": sum(s["endMs"] - s["startMs"] for s in realized if s["origin"] == "task"),
            "contactsReceived": 0,
        }
    horizon = (bundle["clock"]["end"]) * MINUTE

    m = node["metrics"]
    closed = [t for t in tasks if t["outcome"] in ("accepted", "done", "handed_off")]
    metrics = {
        "requests": {"raised": len({t["questId"] for t in tasks}), "resolved": 0, "unresolved": 0,
                     "outcomes": [t["outcome"] for t in tasks], "resolutionPaths": []},
        "waitMs": {"resolvedOnly": [], "meanMinutesResolvedOnly": m.get("resolveMinutes"),
                   "censoredCount": 0, "note": "전시 기록의 값 (확인까지 걸린 분)"},
        "contacts": {"attempts": sum(1 for t in tasks if t["type"] == "contact"), "byResult": {},
                     "toSubject": 0, "note": "전시 기록"},
        "residentBurden": {}, "neighbourMinutes": 0,
        "exhibition": {**m, "tasks": len(tasks), "closedTasks": len(closed)},
    }
    attempt = Attempt(
        id=attempt_id, parentId=parent_attempt, label="%d일차 · %s" % (node["day"], node["title"]),
        policyId=policy.id, scenarioDeckId=DECK, personaRevisionId="persona-exhibition-anon",
        baselineRevisionId="baseline-exhibition", resourceRevisionId="assumed-resources-transport-v1",
        seed=0, status=AttemptStatus.completed, adapter="rule", institutionAdapter="rule",
        environmentRevisionId="env-exhibition", createdAt=bundle["generatedAt"],
        eventCount=len(events), dataSource=DATA_SOURCE)
    result = SimpleNamespace(
        attempt=attempt, events=events, decisions=[], observations=[], reviews=[],
        timeline={"horizonMs": horizon, "actors": actors}, trace=[], metrics=metrics,
        scenes={"source": DATA_SOURCE, "model": scene["model"], "day": node["day"],
                "title": node["title"], "summary": node["summary"], "people": names,
                "episodes": episodes, "panels": panels,
                # A Task id that is not in this day is a mistake in FEATURED, not something to skip quietly.
                "featured": featured_of(node, panels)})
    return result, experienced


def fingerprint(events: list[DomainEvent]) -> str:
    h = hashlib.sha256()
    for e in events:
        h.update(json.dumps(e.model_dump(mode="json"), sort_keys=True, ensure_ascii=False).encode())
    return h.hexdigest()[:16]


def featured_of(node: dict[str, Any], panels: dict[str, Any]) -> list[str]:
    wanted = FEATURED.get(node["day"], [])
    missing = [t for t in wanted if t not in panels]
    if missing:
        raise SystemExit("핵심 장면으로 정한 Task 가 %d일차에 없습니다: %s" % (node["day"], ", ".join(missing)))
    return list(wanted)


def day_summary(bundle: dict[str, Any], node: dict[str, Any]) -> dict[str, Any]:
    """What the wall said of a day: its title, how many requests, and who took
    the hand-offs (the day-end strip and the three-day table read these)."""
    handed = [t for t in node["tasks"] if t["outcome"] == "handed_off"]
    who = sorted({bundle["roles"][a] for t in handed for a in t["actors"]
                  if a in bundle["roles"] and bundle["roles"][a] != "MEDial"})
    # A request is something MEDial took part in. A scene it was never in (two brothers on a
    # pier) happened, but is not a request it received, and the day-end line must not count it.
    medial = {t["questId"] for t in node["tasks"]
              if any("MED" in b["cast"] for b in t["beats"])}
    return {"dayTitle": node["title"], "quests": len(medial),
            "handoff": " · ".join(who) if who else ("있음" if handed else "없음")}


# ------------------------------------------------------------------ pictures
def copy_art(html: Path) -> list[str]:
    """The two pictures the wall drew and the app has not: someone giving chest
    compressions to a person lying down, drawn as one picture (their bodies
    touch). Copied out of the wall page, where they are inlined."""
    text = html.read_text(encoding="utf-8")
    added = []
    folder = art_dir()
    index_path = folder / "index.json"
    index = json.loads(index_path.read_text(encoding="utf-8")) if index_path.exists() else {}
    for name, mime, data in re.findall(r'"([A-Z0-9]+\.cpr\+[A-Z0-9]+\.lying)":"data:image/([a-z]+);base64,([^"]+)"', text):
        target = folder / ("%s.webp" % name)
        if mime != "webp":
            raise SystemExit("그림 형식이 webp가 아닙니다: %s (%s)" % (name, mime))
        if not target.exists():
            target.write_bytes(base64.b64decode(data))
            added.append(name)
        index.setdefault(name, {"file": target.name, "source": "exhibition-2026-09-28 벽 화면에서 옮김"})
    index_path.write_text(json.dumps(index, ensure_ascii=False, indent=1), encoding="utf-8")
    return added


# ------------------------------------------------------------------ main
def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--bundle", type=Path, default=BUNDLE)
    parser.add_argument("--html", type=Path, default=WALL)
    parser.add_argument("--out", type=Path, default=None,
                        help="다른 곳에 만든다 (기본: sim 버전의 기록)")
    parser.add_argument("--replace", action="store_true",
                        help="이미 있는 sim 기록을 local-archive/ 로 옮기고 새로 만든다")
    args = parser.parse_args()

    if not args.bundle.exists():
        print("전시 묶음이 없습니다: %s" % args.bundle)
        return 2
    target = args.out or database_path(SIM, {})
    if target.exists():
        if not args.replace:
            print("sim 기록이 이미 있습니다: %s — 옮기고 새로 만들려면 --replace" % target)
            return 2
        # An earlier import of this record is made again from the bundle, so it
        # goes; anything else (a real run frozen into sim) is kept aside.
        db = sqlite3.connect(target)
        try:
            ours = db.execute("SELECT 1 FROM sqlite_master WHERE name = 'iteration_sessions'").fetchone() \
                and db.execute("SELECT 1 FROM iteration_sessions WHERE id = ?", (SESSION_ID,)).fetchone()
            only = ours and db.execute("SELECT count(*) FROM iteration_sessions").fetchone()[0] == 1
        finally:
            db.close()  # before the file is removed: Windows will not delete an open one
        if only:
            target.unlink()
            print("이전에 가져온 전시 기록을 지우고 다시 만듭니다.")
        else:
            keep = ROOT / "local-archive" / ("sim-before-exhibition-%s.sqlite3"
                                             % datetime.now().strftime("%Y%m%d-%H%M%S"))
            shutil.move(str(target), keep)
            print("있던 sim 기록을 옮겼습니다: %s" % keep.relative_to(ROOT))

    bundle = json.loads(args.bundle.read_text(encoding="utf-8"))
    village = load_village()
    if not village.map_image:
        print("원자료 마을 등록부가 없습니다 (합성 마을로는 가져올 수 없습니다).")
        return 2
    names = {p["id"]: p["name"] for p in bundle["people"]}
    by_id = {n["id"]: n for n in bundle["nodes"]}
    store = Store(target)
    stamp = now()

    session = IterationSession(
        id=SESSION_ID, label="은점마을 사흘 — 전시 기록 (9경로)",
        coreItem="응답이 없거나 도움이 필요할 때 누구의 시간으로 해결할 것인가",
        briefRevision="brief-exhibition-0928", initialSnapshotRef="exhibition-%s" % bundle["generatedAt"],
        initialSnapshotHash=hashlib.sha256(args.bundle.read_bytes()).hexdigest()[:32],
        personaRevisionId="persona-exhibition-anon", worldRevisionId="village-%s" % village.content_hash[:16],
        resourceRevisionId="assumed-resources-transport-v1", developmentDeckRefs=[DECK],
        criteriaRevision=DEFAULT_CRITERIA, basePolicyRevisionId="policy-exh-0",
        maxGenerations=3, maxChangeSetsPerGeneration=3,
        behaviourAdapter="rule", institutionAdapter="rule", reviewAdapter="llm", improvementAdapter="rule",
        status=SessionStatus.ready_for_designer, stopReason="exhibition_record",
        stopDetail=("전시 생성기(local-archive/exhibition-2026-09-28)가 만든 기록이다. 첫 설정 하나에서 날마다 "
                    "디자이너의 요청 셋을 모두 미리 돌려 두었다 — 앱의 엔진이 만든 것이 아니다."),
        currentGenerationIndex=2, createdAt=bundle["generatedAt"], updatedAt=stamp)
    store.save_session(session)

    policies: dict[str, PolicyRevision] = {}
    attempts: dict[str, str] = {}
    for node in bundle["nodes"]:
        parent = by_id.get(node["parent"]) if node["parent"] is not None else None
        policy = policy_of(node, values_for(node, by_id), policies[parent["id"]].id if parent else None)
        policies[node["id"]] = policy
        store.save_policy(policy)
        attempt_id = "att-exh-%s" % node["id"]
        result, experienced = build_day(bundle, node, village, policy, attempt_id,
                                        attempts.get(parent["id"]) if parent else None, names)
        store.save_run(result, policy, fingerprint(result.events))
        attempts[node["id"]] = attempt_id

        gen_id = "gen-exh-%s" % node["id"]
        reviews = []
        scene = bundle["scenes"][node["key"]]
        for said in scene["reviews"]:
            who = actor(said["speaker"])
            reviews.append(AgentReview(
                id="rev-exh-%s-%s" % (node["id"], who), sessionId=SESSION_ID, generationIndex=node["day"] - 1,
                attemptId=attempt_id, actorId=who,
                actorRole="village_head" if who == "P6" else "resident", policyRevisionId=policy.id,
                adapter="llm", usageStatus=UsageStatus.used,
                experiencedEventIds=sorted(set(experienced.get(who, [])), key=lambda e: int(e.split("-")[1])),
                items=[], overallNarrative=said["text"], model={"id": scene["model"], "source": DATA_SOURCE},
                createdAt=bundle["generatedAt"]))
        change_sets = []
        for i, option in enumerate(node.get("options") or []):
            semantic = semantic_rules.build_change(
                option["ruleType"], policy.model_dump(mode="json"),
                semantic_rules.merge_after(option["ruleType"], policy.model_dump(mode="json"), option["after"]))
            child = by_id.get("%s-%d" % (node["id"], i))
            # The request the designer makes (title), what it is for (goal), what a resident lived
            # through that it answers (because) and which resident and Task that was (evidence).
            # Nothing is invented here: the bundle's request table says all of it.
            evidence = option.get("evidence") or {}
            cited = {"subject": node_subject(node), "helper": "P6", "rider": "P9"}.get(evidence.get("actor"))
            change_sets.append(ChangeSet(
                id="change-exh-%s-%d" % (node["id"], i), sessionId=SESSION_ID,
                generationIndex=node["day"] - 1, baseRevisionId=policy.id, label=option["title"],
                mechanism=option["because"], changes=[materialize_change(semantic)],
                expectedEffects=[option["goal"]] if option.get("goal") else [],
                affectedActors=[cited] if cited else [],
                eventRefs=["%s:%s" % (attempt_id, evidence["task"])] if evidence.get("task") else [],
                watchNext=["다음 날 같은 상황에서 %s이(가) 어떻게 달라지는지" % (names.get(cited, cited))] if cited else [],
                author="rule_draft", validationStatus=ChangeSetValidation.valid,
                confirmationStatus=(ChangeSetConfirmation.confirmed if child else ChangeSetConfirmation.not_run),
                confirmationReason=("전시 기록: 세 요청을 모두 미리 돌려 두었다. 연구자가 하나를 확정한 것이 아니다."
                                    if child else ""),
                resultingAttemptId="att-exh-%s" % child["id"] if child else None,
                resultingPolicyRevisionId="policy-exh-%s" % child["id"] if child else None,
                createdAt=bundle["generatedAt"]))
        generation = Generation(
            id=gen_id, sessionId=SESSION_ID, index=node["day"] - 1,
            parentGenerationId="gen-exh-%s" % parent["id"] if parent else None,
            policyRevisionId=policy.id, label=node["choice"]["title"], attemptIds=[attempt_id],
            reviewIds=[r.id for r in reviews], changeSetIds=[c.id for c in change_sets],
            outcome=GenerationOutcome.advanced if change_sets else GenerationOutcome.final,
            appliedChangeSetId=("change-exh-%s-%s" % (parent["id"], node["id"].rsplit("-", 1)[1])
                                if parent else None),
            confirmedBy="none", confirmationReason=node["choice"].get("because") or "",
            metrics={"exhibition": {**node["metrics"], **day_summary(bundle, node)}},
            createdAt=bundle["generatedAt"])
        store.save_generation(generation)
        if reviews:
            store.save_agent_reviews(gen_id, reviews)
        if change_sets:
            store.save_change_sets(gen_id, change_sets)

    added = copy_art(args.html) if args.html.exists() else []
    print("가져왔습니다: %s" % target)
    print("  날 %d · 세션 1 · 그림 %d장 새로 옮김" % (len(bundle["nodes"]), len(added)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
