"""Build the opening film's map of where the village is (IntroScreen, scene 2).

The film draws a line from KAIST to Namhae and then closes in on Eunjeom. It needs
two pictures of the same land: South Korea at a glance, and the coast around
Namhae island close enough that the village sits on a recognisable shore. Both
come from KOSTAT 2013 boundaries as published by southkorea/southkorea-maps
(provinces, simplified; municipalities, full resolution) and are written as SVG
path strings in kilometres, so the screen projects nothing.

    python scripts/korea_outline.py      # -> src/features/simulation/intro/koreaMap.ts

The two places are public landmarks, not anyone's home: KAIST's main campus and
the village's fishing-village centre in Mulgeon-ri, Samdong-myeon.
"""

from __future__ import annotations

import json
import math
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "features" / "simulation" / "intro" / "koreaMap.ts"
BASE = "https://raw.githubusercontent.com/southkorea/southkorea-maps/master/kostat/2013/json/"

#: Projection: equirectangular around 35.5N, in km. Good to a percent over the peninsula.
LON0, LAT0 = 124.5, 38.7
KX, KY = 111.32 * math.cos(math.radians(35.5)), 110.9

#: The close-up: every municipality with land in this box (lon, lat) is drawn at
#: full detail - Namhae and the shores facing it. Wider than the film's frame, so
#: no edge of the close-up shows sea where there is land.
CLOSE_BOX = (127.45, 34.45, 128.55, 35.25)
NAMHAE_CODE = "38350"

KAIST = (127.3604, 36.3721)
NAMHAE_TOWN = (127.8924, 34.8376)
EUNJEOM = (128.0460, 34.7960)


def project(lon: float, lat: float) -> tuple[float, float]:
    return (lon - LON0) * KX, (LAT0 - lat) * KY


def simplify(points: list[tuple[float, float]], tol: float) -> list[tuple[float, float]]:
    """Douglas-Peucker, iterative."""
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]
        bx, by = points[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy)
        worst, at = 0.0, -1
        for i in range(a + 1, b):
            px, py = points[i]
            # A ring starts and ends on one point: measure from it, not from a line.
            d = abs(dy * (px - ax) - dx * (py - ay)) / norm if norm else math.hypot(px - ax, py - ay)
            if d > worst:
                worst, at = d, i
        if worst > tol and at > 0:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(points, keep) if k]


def area(points: list[tuple[float, float]]) -> float:
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(points, points[1:] + points[:1]))) / 2


def rings(geometry: dict) -> list[list[list[float]]]:
    polys = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    return [poly[0] for poly in polys]  # outer rings: the land, not its lakes


def in_box(feature: dict) -> bool:
    w, s_, e, n = CLOSE_BOX
    return any(w <= lon <= e and s_ <= lat <= n for ring in rings(feature["geometry"]) for lon, lat in ring)


def path(features: list[dict], tol: float, min_area: float) -> str:
    out = []
    for feature in features:
        for ring in rings(feature["geometry"]):
            pts = simplify([project(lon, lat) for lon, lat in ring], tol)
            if len(pts) < 3 or area(pts) < min_area:
                continue
            out.append("M" + "L".join("%.1f %.1f" % p if tol >= 0.3 else "%.2f %.2f" % p for p in pts) + "Z")
    return "".join(out)


def load(name: str) -> dict:
    with urllib.request.urlopen(BASE + name) as response:
        return json.loads(response.read().decode("utf-8"))


def main() -> None:
    provinces = load("skorea_provinces_geo_simple.json")["features"]
    municipalities = [f for f in load("skorea_municipalities_geo.json")["features"] if in_box(f)]
    namhae = [f for f in municipalities if f["properties"]["code"] == NAMHAE_CODE]
    rest = [f for f in municipalities if f["properties"]["code"] != NAMHAE_CODE]
    point = lambda p: "[%.2f, %.2f]" % project(*p)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/korea_outline.py from KOSTAT 2013 boundaries\n"
        "// (southkorea/southkorea-maps). Kilometres, equirectangular around 35.5N, north up.\n"
        "// Do not edit by hand.\n\n"
        "/** South Korea at a glance: provinces, simplified. */\n"
        f"export const KOREA = '{path(provinces, 0.8, 4)}';\n\n"
        "/** Namhae island, at close-up detail. */\n"
        f"export const NAMHAE = '{path(namhae, 0.06, 0.02)}';\n\n"
        "/** The shores around it, a little coarser. */\n"
        f"export const NEAR = '{path(rest, 0.12, 0.08)}';\n\n"
        f"export const KAIST: [number, number] = {point(KAIST)};\n"
        f"export const NAMHAE_TOWN: [number, number] = {point(NAMHAE_TOWN)};\n"
        f"export const EUNJEOM: [number, number] = {point(EUNJEOM)};\n",
        encoding="utf-8")
    print("wrote %s (%d KB)" % (OUT.relative_to(ROOT), OUT.stat().st_size // 1024))


if __name__ == "__main__":
    main()
