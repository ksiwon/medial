const noop = () => {};
/**
 * Mount the observe screen on a stored run with the playhead at a chosen point.
 * `at` picks the point from the run's own reel, so a test names what it wants
 * to be looking at (a clock time on the map, or one event's line) rather than a
 * number of seconds.
 */
function observe({ run = detail, log = events, at }: {
  run?: AttemptDetail;
  log?: DomainEvent[];
  at?: { ms: number } | { seq: number };
} = {}) {
  usePlayback.setState({ viewMode: 'researcher', playing: false });
  usePlayback.getState().load({ attemptId: run.attempt.id, detail: run, events: log, village });
  const reel = usePlayback.getState().reel!;
  const rt = !at ? 0 : 'ms' in at ? reel.atTime(at.ms) : reel.atSeq(at.seq);
  usePlayback.setState({ rt, position: reel.locate(rt) });
  return render(
    <ObserveScreen village={village} detail={run} events={log} art={new Set()}
      dayEnd={{ text: '하루가 끝났습니다', action: '주민 평가 읽기 →' }}
      onReadEvaluations={noop} />,
  );
}

const hour = (h: number) => ({ ms: h * 3_600_000 });
/** The first event of this type, as a playhead target. */
const first = (type: string, log = events) => ({ seq: log.find((e) => e.type === type)!.seq });

